CREATE TABLE IF NOT EXISTS schema_migrations (
  version integer PRIMARY KEY,
  name varchar(200) NOT NULL,
  checksum char(64) NOT NULL,
  applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email varchar(320) NOT NULL,
  display_name varchar(150) NOT NULL,
  role varchar(10) NOT NULL CHECK (role IN ('admin', 'user')),
  password_hash varchar(300) NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_normalized ON users (upper(btrim(email)));

CREATE TABLE IF NOT EXISTS user_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash char(64) NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz
);
CREATE INDEX IF NOT EXISTS ix_user_sessions_user_expiry ON user_sessions(user_id, expires_at) INCLUDE (revoked_at);

CREATE TABLE IF NOT EXISTS one_time_tokens (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash char(64) NOT NULL UNIQUE,
  purpose varchar(16) NOT NULL CHECK (purpose IN ('activation', 'recovery')),
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  used_at timestamptz
);

CREATE TABLE IF NOT EXISTS visualisations (
  id uuid PRIMARY KEY,
  name varchar(160) NOT NULL,
  kind varchar(16) NOT NULL CHECK (kind IN ('visualisation', 'system')),
  is_protected boolean NOT NULL DEFAULT false,
  is_deleted boolean NOT NULL DEFAULT false,
  owner_id uuid REFERENCES users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_visualisations_catalogue ON visualisations(is_deleted, kind, updated_at);
CREATE UNIQUE INDEX IF NOT EXISTS uq_visualisations_live_name ON visualisations(upper(name)) WHERE is_deleted = false;

CREATE TABLE IF NOT EXISTS visualisation_drafts (
  visualisation_id uuid PRIMARY KEY REFERENCES visualisations(id) ON DELETE CASCADE,
  document_json jsonb NOT NULL,
  revision integer NOT NULL DEFAULT 1,
  updated_by uuid REFERENCES users(id),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS visualisation_versions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  visualisation_id uuid NOT NULL REFERENCES visualisations(id),
  version_number integer NOT NULL,
  document_json jsonb NOT NULL,
  published_by uuid REFERENCES users(id),
  published_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (visualisation_id, version_number)
);
CREATE INDEX IF NOT EXISTS ix_visualisation_versions_latest ON visualisation_versions(visualisation_id, version_number DESC);

CREATE TABLE IF NOT EXISTS templates (
  id uuid PRIMARY KEY,
  name varchar(160) NOT NULL,
  description varchar(500) NOT NULL,
  document_json jsonb NOT NULL,
  is_system boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS assets (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  file_name varchar(260) NOT NULL,
  content_type varchar(120) NOT NULL,
  size_bytes bigint NOT NULL CHECK (size_bytes > 0),
  sha256 char(64) NOT NULL,
  storage_key varchar(600) NOT NULL,
  created_by uuid REFERENCES users(id),
  environment varchar(20) NOT NULL DEFAULT 'development' CHECK (environment IN ('development', 'production')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS draft_assets (
  visualisation_id uuid NOT NULL REFERENCES visualisation_drafts(visualisation_id) ON DELETE CASCADE,
  asset_id uuid NOT NULL REFERENCES assets(id),
  PRIMARY KEY (visualisation_id, asset_id)
);

CREATE TABLE IF NOT EXISTS version_assets (
  version_id uuid NOT NULL REFERENCES visualisation_versions(id),
  asset_id uuid NOT NULL REFERENCES assets(id),
  PRIMARY KEY (version_id, asset_id)
);

CREATE TABLE IF NOT EXISTS devices (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name varchar(160) NOT NULL,
  credential_hash char(64),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz
);

CREATE TABLE IF NOT EXISTS audit_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid REFERENCES users(id),
  action varchar(80) NOT NULL,
  entity_type varchar(60) NOT NULL,
  entity_id varchar(80),
  details_json jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_audit_events_created_at ON audit_events(created_at DESC);

CREATE OR REPLACE VIEW vw_visualisation_overview AS
SELECT v.id, v.name, v.kind, v.is_protected, v.owner_id, u.display_name AS owner_name,
       v.created_at, v.updated_at, d.revision,
       (SELECT max(x.version_number) FROM visualisation_versions x WHERE x.visualisation_id = v.id) AS latest_published_version
FROM visualisations v
LEFT JOIN users u ON u.id = v.owner_id
LEFT JOIN visualisation_drafts d ON d.visualisation_id = v.id
WHERE v.is_deleted = false;

CREATE OR REPLACE VIEW vw_publication_history AS
SELECT x.id AS version_id, x.visualisation_id, v.name, x.version_number,
       x.published_by, u.display_name AS published_by_name, x.published_at
FROM visualisation_versions x
JOIN visualisations v ON v.id = x.visualisation_id
LEFT JOIN users u ON u.id = x.published_by;

CREATE OR REPLACE VIEW vw_asset_usage AS
SELECT a.id AS asset_id, a.file_name, a.content_type, a.size_bytes, a.sha256,
       (SELECT count(*) FROM draft_assets d WHERE d.asset_id = a.id) AS draft_references,
       (SELECT count(*) FROM version_assets x WHERE x.asset_id = a.id) AS published_references,
       a.created_at
FROM assets a;

CREATE OR REPLACE VIEW vw_user_overview AS
SELECT u.id, u.email, u.display_name, u.role, u.is_active, u.created_at, u.updated_at,
       (SELECT count(*) FROM user_sessions s
        WHERE s.user_id = u.id AND s.revoked_at IS NULL AND s.expires_at > now()) AS active_sessions
FROM users u;

CREATE OR REPLACE VIEW vw_audit_timeline AS
SELECT a.id, a.user_id, u.display_name AS actor_name, a.action, a.entity_type,
       a.entity_id, a.details_json, a.created_at
FROM audit_events a
LEFT JOIN users u ON u.id = a.user_id;

